#!/usr/bin/env python3
"""Generate COMMANDS.md from the live registered tool surface.

Run after adding/removing tools; CI's test_tool_surface asserts the file is
in sync so the count can't silently drift (the 280-vs-293 problem).
"""
import os

from unrealmcp._bridge import mcp
import unrealmcp.tools  # noqa: F401 — registers every @mcp.tool()

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "COMMANDS.md")


def _first_line(desc: str) -> str:
    for line in (desc or "").strip().splitlines():
        if line.strip():
            return line.strip()
    return ""


def _collect():
    rows = []
    for name, t in mcp._tool_manager._tools.items():
        module = getattr(getattr(t, "fn", None), "__module__", "") or ""
        module = module.replace("unrealmcp.tools.", "")
        rows.append((name, module, _first_line(getattr(t, "description", "") or "")))
    return sorted(rows)


def main() -> None:
    rows = _collect()
    lines = [
        "# UnrealMCP — Command Reference",
        "",
        f"**{len(rows)} tools** (generated by `scripts/gen_command_manifest.py` — do not edit by hand).",
        "",
        "| Tool | Module | Description |",
        "| --- | --- | --- |",
    ]
    for name, module, desc in rows:
        desc = desc.replace("|", "\\|")
        lines.append(f"| `{name}` | {module} | {desc} |")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} with {len(rows)} tools")


if __name__ == "__main__":
    main()
